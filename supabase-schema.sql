create table if not exists public.wishes (
    id bigint generated by default as identity primary key,
    guest_name text not null check (char_length(btrim(guest_name)) between 1 and 120),
    message text not null check (char_length(btrim(message)) between 1 and 2000),
    created_at timestamptz not null default now()
);

create table if not exists public.reservations (
    id bigint generated by default as identity primary key,
    guest_name text not null check (char_length(btrim(guest_name)) between 1 and 120),
    attending boolean not null,
    guest_count integer not null check (guest_count between 0 and 20),
    created_at timestamptz not null default now(),
    constraint reservation_guest_count_matches_attendance
        check ((attending and guest_count >= 1) or (not attending and guest_count = 0))
);

alter table public.wishes enable row level security;
alter table public.reservations enable row level security;

grant select, insert on public.wishes to anon;
grant usage on sequence public.wishes_id_seq to anon;

drop policy if exists "Anyone can read wishes" on public.wishes;
create policy "Anyone can read wishes"
    on public.wishes for select to anon
    using (true);

drop policy if exists "Anyone can submit wishes" on public.wishes;
create policy "Anyone can submit wishes"
    on public.wishes for insert to anon
    with check (true);

drop policy if exists "Anyone can submit reservations" on public.reservations;
revoke insert on public.reservations from anon;
revoke usage on sequence public.reservations_id_seq from anon;

create table if not exists public.guest_invitations (
    id uuid primary key default gen_random_uuid(),
    guest_name text not null check (char_length(btrim(guest_name)) between 1 and 120),
    max_guests smallint not null default 1 check (max_guests between 1 and 20),
    token_hash text not null unique check (token_hash ~ '^[0-9a-f]{64}$'),
    rsvp_status text not null default 'pending'
        check (rsvp_status in ('pending', 'attending', 'declined')),
    rsvp_guest_count smallint not null default 0,
    checked_in_count smallint not null default 0,
    checked_in_at timestamptz,
    checked_in_by uuid references auth.users(id),
    created_at timestamptz not null default now(),
    constraint guest_rsvp_count_within_limit check (
        (rsvp_status = 'attending' and rsvp_guest_count between 1 and max_guests)
        or (rsvp_status in ('pending', 'declined') and rsvp_guest_count = 0)
    ),
    constraint guest_checkin_count_within_rsvp check (
        checked_in_count between 0 and rsvp_guest_count
    ),
    constraint guest_checkin_timestamp_matches_count check (
        (checked_in_count = 0 and checked_in_at is null)
        or (checked_in_count > 0 and rsvp_status = 'attending' and checked_in_at is not null)
    )
);

alter table public.guest_invitations enable row level security;
revoke all on table public.guest_invitations from anon, authenticated;
alter table public.guest_invitations
    add column if not exists checked_in_by uuid references auth.users(id);

create table if not exists public.checkin_staff (
    user_id uuid primary key references auth.users(id) on delete cascade,
    created_at timestamptz not null default now()
);

alter table public.checkin_staff enable row level security;
revoke all on table public.checkin_staff from anon, authenticated;

drop function if exists public.check_in_guest(text);

create or replace function public.check_in_guest(p_token_hash text, p_checked_in_by uuid)
returns table (
    guest_name text,
    rsvp_guest_count smallint,
    checked_in_count smallint,
    checked_in_at timestamptz,
    checked_in_by uuid
)
language sql
security definer
set search_path = ''
as $$
    update public.guest_invitations as invitation
    set checked_in_count = invitation.rsvp_guest_count,
        checked_in_at = now(),
        checked_in_by = p_checked_in_by
    where invitation.token_hash = p_token_hash
      and invitation.rsvp_status = 'attending'
      and invitation.checked_in_count = 0
    returning invitation.guest_name,
              invitation.rsvp_guest_count,
              invitation.checked_in_count,
              invitation.checked_in_at,
              invitation.checked_in_by;
$$;

revoke all on function public.check_in_guest(text, uuid) from public, anon, authenticated;
grant execute on function public.check_in_guest(text, uuid) to service_role;